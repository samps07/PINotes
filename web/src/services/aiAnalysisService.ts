// Browser-local storage keys so the user can configure a separate AI API key & prompt on Web vs Android
const WEB_AI_API_KEY_STORAGE = 'pinotes_web_ai_api_key_v1';
const WEB_AI_PROMPT_STORAGE = 'pinotes_web_ai_prompt_v1';

export interface AiAnalysisResult {
  title: string;
  content: string;
  imageUrl: string;
  category: string | null;
  tags: string | null;
  resolvedUrl: string | null;
}

export function getWebAiApiKey(): string {
  try {
    return (localStorage.getItem(WEB_AI_API_KEY_STORAGE) || '').trim();
  } catch {
    return '';
  }
}

export function saveWebAiApiKey(apiKey: string): void {
  try {
    const clean = apiKey.trim();
    if (clean) {
      localStorage.setItem(WEB_AI_API_KEY_STORAGE, clean);
    } else {
      localStorage.removeItem(WEB_AI_API_KEY_STORAGE);
    }
  } catch {
    // ignore storage errors
  }
}

export function getWebAiPrompt(): string {
  try {
    const stored = (localStorage.getItem(WEB_AI_PROMPT_STORAGE) || '').trim();
    return stored || DEFAULT_SYSTEM_INSTRUCTION;
  } catch {
    return DEFAULT_SYSTEM_INSTRUCTION;
  }
}

export function saveWebAiPrompt(prompt: string): void {
  try {
    localStorage.setItem(WEB_AI_PROMPT_STORAGE, prompt);
  } catch {
    // ignore storage errors
  }
}

export function resetWebAiPrompt(): string {
  try {
    localStorage.removeItem(WEB_AI_PROMPT_STORAGE);
  } catch {
    // ignore
  }
  return DEFAULT_SYSTEM_INSTRUCTION;
}

export function extractUrlFromText(text: string): string | null {
  const match = text.match(/(https?:\/\/[^\s$.?#].[^\s]*)/i);
  return match ? match[1].replace(/[),.;]+$/, '') : null;
}

export function isMapUrl(url: string | null | undefined): boolean {
  if (!url || !url.trim()) return false;
  const lower = url.toLowerCase().trim();
  return (
    lower.includes('maps.google.') ||
    lower.includes('google.com/maps') ||
    lower.includes('maps.app.goo.gl') ||
    lower.includes('goo.gl/maps') ||
    lower.includes('maps.apple.com') ||
    lower.includes('apple.com/maps') ||
    lower.includes('waze.com') ||
    lower.includes('openstreetmap.org') ||
    lower.includes('bing.com/maps') ||
    lower.includes('here.com') ||
    lower.includes('mapquest.com') ||
    lower.includes('maps.me') ||
    lower.includes('plus.codes') ||
    lower.includes('citymapper.com') ||
    lower.includes('/maps') ||
    lower.includes('maps.') ||
    lower.includes('map.') ||
    lower.includes('maplink') ||
    lower.includes('location') ||
    lower.startsWith('geo:') ||
    lower.startsWith('google.navigation:') ||
    lower.startsWith('google.streetview:')
  );
}

interface ScrapedPreview {
  title: string;
  description: string;
  imageUrl: string;
}

function guessTitleFromUrl(url: string): string {
  try {
    const host = new URL(url).hostname.replace(/^www\./i, '');
    return host.charAt(0).toUpperCase() + host.slice(1);
  } catch {
    return 'Web Bookmark';
  }
}

async function fetchCorsSafeUrlPreview(url: string): Promise<ScrapedPreview> {
  const fallback: ScrapedPreview = {
    title: guessTitleFromUrl(url),
    description: `Web Link shared: ${url}`,
    imageUrl: '',
  };

  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 4500);
    const resp = await fetch(
      `https://api.microlink.io/?url=${encodeURIComponent(url)}`,
      { signal: controller.signal }
    );
    clearTimeout(timer);
    if (!resp.ok) return fallback;

    const json = (await resp.json()) as {
      status?: string;
      data?: {
        title?: string;
        description?: string;
        image?: { url?: string };
        logo?: { url?: string };
      };
    };

    if (json.status === 'success' && json.data) {
      return {
        title: json.data.title?.trim() || fallback.title,
        description: json.data.description?.trim() || fallback.description,
        imageUrl: json.data.image?.url?.trim() || json.data.logo?.url?.trim() || '',
      };
    }
  } catch {
    // CORS, offline, or timeout — continue smoothly with AI world knowledge
  }

  return fallback;
}

function stripCodeFences(text: string): string {
  let clean = text.trim();
  if (/^```json/i.test(clean)) {
    clean = clean.replace(/^```json/i, '').trim();
  } else if (clean.startsWith('```')) {
    clean = clean.replace(/^```/, '').trim();
  }
  if (clean.endsWith('```')) {
    clean = clean.slice(0, -3).trim();
  }
  const start = clean.indexOf('{');
  const end = clean.lastIndexOf('}');
  if (start >= 0 && end > start) {
    clean = clean.slice(start, end + 1);
  }
  return clean;
}

function normalizeTags(raw: unknown): string | null {
  if (typeof raw !== 'string' || !raw.trim()) return null;
  const cleaned = raw
    .split(/[|,]+/)
    .map((t) => t.trim().replace(/^#/, '').trim())
    .filter(Boolean);
  return cleaned.length > 0 ? cleaned.join('|') : null;
}

export async function analyzeWithAi(
  rawInput: string,
  context?: { existingTitle?: string; existingContent?: string; webUrl?: string }
): Promise<AiAnalysisResult> {
  const apiKey = getWebAiApiKey();
  if (!apiKey) {
    throw new Error(
      'Web AI API key is not configured. Open Settings (top right) -> AI API Key Config to set your OpenRouter or Groq key.'
    );
  }

  const combinedSource =
    rawInput.trim() ||
    context?.webUrl?.trim() ||
    [context?.existingTitle, context?.existingContent].filter(Boolean).join('\n').trim();

  if (!combinedSource) {
    throw new Error('Enter a webpage URL, title, or note text for AI analysis.');
  }

  const detectedUrl = extractUrlFromText(combinedSource);
  if (detectedUrl && isMapUrl(detectedUrl) && combinedSource === detectedUrl) {
    throw new Error('Map/location links are skipped from webpage scraping.');
  }

  const ogMeta: ScrapedPreview = detectedUrl
    ? await fetchCorsSafeUrlPreview(detectedUrl)
    : { title: '', description: '', imageUrl: '' };

  const customInstructions = getWebAiPrompt();
  const hasJsonContract =
    /json/i.test(customInstructions) &&
    customInstructions.includes('title') &&
    (customInstructions.includes('content') || customInstructions.includes('summary'));

  const systemInstruction = hasJsonContract
    ? customInstructions
    : `${customInstructions}

Mandatory Output Format Contract:
You MUST return ONLY valid JSON with these keys:
{
  "title": "...",
  "content": "...",
  "summary": "...",
  "imageUrl": "...",
  "category": "...",
  "tags": "..."
}`;

  const prompt = detectedUrl
    ? `Link: ${detectedUrl}
Additional Note Context: ${combinedSource !== detectedUrl ? combinedSource : '(none)'}

Local Scraper suggestions:
Title: ${ogMeta.title || '(not available)'}
Description/Snippet: ${ogMeta.description || '(not available)'}
Image: ${ogMeta.imageUrl || '(not available)'}

Extract the webpage metadata and return ONLY JSON with:
{
  "title": "...",
  "content": "...",
  "imageUrl": "...",
  "category": "...",
  "tags": "..."
}

If image/poster is not available, set imageUrl to empty.
If some info is not available, try to infer it using your pre-trained world knowledge.`
    : `Analyze and curate the following topic, title, or note text:
${combinedSource}

Return ONLY valid JSON with:
{
  "title": "...",
  "content": "...",
  "imageUrl": "...",
  "category": "...",
  "tags": "..."
}

If no reliable direct image URL is known, leave "imageUrl" blank ("").`;

  const isOpenRouter =
    apiKey.includes('sk-or') ||
    apiKey.startsWith('sk-or') ||
    (apiKey.startsWith('sk-') && !apiKey.startsWith('gsk_'));

  const chatUrl = isOpenRouter
    ? 'https://openrouter.ai/api/v1/chat/completions'
    : 'https://api.groq.com/openai/v1/chat/completions';

  const modelsToTry = isOpenRouter
    ? [
        'openai/gpt-4o-mini',
        'google/gemini-2.5-flash',
        'meta-llama/llama-3.3-70b-instruct',
        'auto',
      ]
    : ['llama-3.3-70b-versatile', 'llama-3.1-8b-instant', 'mixtral-8x7b-32768'];

  let lastErrorMsg = '';

  for (const model of modelsToTry) {
    for (const useJsonMode of [true, false]) {
      try {
        const headers: Record<string, string> = {
          Authorization: `Bearer ${apiKey}`,
          'Content-Type': 'application/json',
        };
        if (isOpenRouter) {
          headers['HTTP-Referer'] = window.location.origin || 'https://pinotes.web';
          headers['X-OpenRouter-Title'] = 'PINotes Web';
        }

        const body: Record<string, unknown> = {
          model,
          messages: [
            { role: 'system', content: systemInstruction },
            { role: 'user', content: prompt },
          ],
          temperature: 0.2,
        };
        if (useJsonMode) {
          body.response_format = { type: 'json_object' };
        }

        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), 35000);
        const resp = await fetch(chatUrl, {
          method: 'POST',
          headers,
          body: JSON.stringify(body),
          signal: controller.signal,
        });
        clearTimeout(timer);

        const rawText = await resp.text();
        if (!resp.ok) {
          // Capture concise error message; retry without json_object only if 400
          try {
            const errJson = JSON.parse(rawText) as { error?: { message?: string } };
            lastErrorMsg = errJson.error?.message || `HTTP ${resp.status}`;
          } catch {
            lastErrorMsg = `HTTP ${resp.status}`;
          }
          if (resp.status === 401 || resp.status === 403) {
            throw new Error(`Invalid API Key (${lastErrorMsg}). Check Settings -> AI API Key Config.`);
          }
          if (resp.status === 400 && useJsonMode) {
            continue;
          }
          break;
        }

        const parsedResp = JSON.parse(rawText) as {
          choices?: Array<{ message?: { content?: string } }>;
        };
        const contentText = parsedResp.choices?.[0]?.message?.content?.trim() || '';
        if (!contentText) break;

        const cleanJsonStr = stripCodeFences(contentText);
        const extracted = JSON.parse(cleanJsonStr) as Record<string, unknown>;

        const title =
          (typeof extracted.title === 'string' && extracted.title.trim()) ||
          ogMeta.title ||
          context?.existingTitle ||
          'Curated Note';

        const content =
          (typeof extracted.content === 'string' && extracted.content.trim()) ||
          (typeof extracted.summary === 'string' && extracted.summary.trim()) ||
          ogMeta.description ||
          '';

        let imageUrl =
          typeof extracted.imageUrl === 'string' ? extracted.imageUrl.trim() : '';
        if (!imageUrl || !/^https?:\/\//i.test(imageUrl)) {
          imageUrl = ogMeta.imageUrl;
        }

        const category =
          typeof extracted.category === 'string' && extracted.category.trim()
            ? extracted.category.trim()
            : null;

        const tags = normalizeTags(extracted.tags);

        return {
          title,
          content,
          imageUrl,
          category,
          tags,
          resolvedUrl: detectedUrl,
        };
      } catch (err: unknown) {
        if (err instanceof Error && err.message.startsWith('Invalid API Key')) {
          throw err;
        }
        lastErrorMsg = err instanceof Error ? err.message : 'Network error during AI analysis';
        if (!useJsonMode) break;
      }
    }
  }

  // Fallback to OpenGraph result if URL metadata was scraped cleanly and AI didn't reject the API key
  if (detectedUrl && ogMeta.title && ogMeta.description && !lastErrorMsg.includes('API Key')) {
    return {
      title: ogMeta.title,
      content: ogMeta.description,
      imageUrl: ogMeta.imageUrl,
      category: 'Reference',
      tags: null,
      resolvedUrl: detectedUrl,
    };
  }

  throw new Error(
    lastErrorMsg
      ? `AI analysis failed: ${lastErrorMsg}`
      : 'AI analysis could not extract metadata. Verify your API key and input.'
  );
}
